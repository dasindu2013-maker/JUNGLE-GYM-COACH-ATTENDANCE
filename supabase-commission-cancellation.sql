-- Run in Jungle Gym COACH ATTENDANCE, not Membership Supabase.
-- Adds cancellation support. Does not cancel any existing commission.
BEGIN;

ALTER TABLE public.membership_commissions
  ADD COLUMN IF NOT EXISTS cancelled_at timestamptz,
  ADD COLUMN IF NOT EXISTS cancelled_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  ADD COLUMN IF NOT EXISTS cancellation_reason text,
  ADD COLUMN IF NOT EXISTS commission_before_cancellation numeric(12,2);

CREATE TABLE IF NOT EXISTS public.membership_commission_cancellations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  commission_id bigint NOT NULL UNIQUE REFERENCES public.membership_commissions(id) ON DELETE RESTRICT,
  source_key text NOT NULL,
  receipt_number text,
  member_name text,
  staff_name text,
  previous_commission numeric(12,2) NOT NULL,
  reason text NOT NULL,
  cancelled_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  cancelled_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.membership_commission_cancellations ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.membership_commission_cancellations FROM PUBLIC, anon, authenticated;
GRANT SELECT ON public.membership_commission_cancellations TO authenticated;
DROP POLICY IF EXISTS commission_cancellation_admin_read ON public.membership_commission_cancellations;
CREATE POLICY commission_cancellation_admin_read
ON public.membership_commission_cancellations FOR SELECT TO authenticated
USING (public.is_admin());

-- The existing sheet-sync RPC can safely run again: a cancelled source_key
-- stays cancelled and its commission remains zero, including ON CONFLICT paths.
CREATE OR REPLACE FUNCTION public.enforce_membership_commission_cancellation()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  previous public.membership_commissions%rowtype;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    IF OLD.cancelled_at IS NOT NULL THEN
      -- Preserve the cancelled receipt's snapshot as well as its zero amount.
      NEW := OLD;
      NEW.commission_amount := 0;
      NEW.updated_at := now();
    ELSIF NEW.cancelled_at IS NOT NULL THEN
      NEW.commission_before_cancellation := OLD.commission_amount;
      NEW.commission_amount := 0;
    END IF;
  ELSE
    SELECT * INTO previous FROM public.membership_commissions
    WHERE source_key = NEW.source_key;
    IF FOUND AND previous.cancelled_at IS NOT NULL THEN
      NEW.cancelled_at := previous.cancelled_at;
      NEW.cancelled_by := previous.cancelled_by;
      NEW.cancellation_reason := previous.cancellation_reason;
      NEW.commission_before_cancellation := previous.commission_before_cancellation;
      NEW.commission_amount := 0;
    END IF;
  END IF;
  RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION public.enforce_membership_commission_cancellation() FROM PUBLIC, anon, authenticated;
DROP TRIGGER IF EXISTS preserve_membership_commission_cancellation ON public.membership_commissions;
CREATE TRIGGER preserve_membership_commission_cancellation
BEFORE INSERT OR UPDATE ON public.membership_commissions
FOR EACH ROW EXECUTE FUNCTION public.enforce_membership_commission_cancellation();

CREATE OR REPLACE FUNCTION public.admin_cancel_membership_commission(
  p_commission_id bigint,
  p_expected_receipt text,
  p_expected_source_key text,
  p_expected_staff text,
  p_expected_commission numeric,
  p_reason text
)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  v_record public.membership_commissions%rowtype;
  v_reason text := btrim(coalesce(p_reason, ''));
BEGIN
  IF NOT coalesce(public.is_admin(), false) THEN
    RAISE EXCEPTION 'Only an administrator can cancel a commission';
  END IF;
  IF length(v_reason) < 5 OR length(v_reason) > 250 THEN
    RAISE EXCEPTION 'Enter a cancellation reason between 5 and 250 characters';
  END IF;
  SELECT * INTO v_record FROM public.membership_commissions
  WHERE id = p_commission_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Commission record was not found. Refresh payroll.'; END IF;
  IF v_record.cancelled_at IS NOT NULL THEN
    RETURN jsonb_build_object('ok', true, 'already_cancelled', true, 'receipt_number', v_record.receipt_number);
  END IF;
  IF v_record.receipt_number IS DISTINCT FROM p_expected_receipt
     OR v_record.source_key IS DISTINCT FROM p_expected_source_key
     OR v_record.staff_name IS DISTINCT FROM p_expected_staff
     OR v_record.commission_amount IS DISTINCT FROM p_expected_commission THEN
    RAISE EXCEPTION 'This commission changed. Refresh payroll and review it again.';
  END IF;
  INSERT INTO public.membership_commission_cancellations (
    commission_id, source_key, receipt_number, member_name, staff_name,
    previous_commission, reason, cancelled_by
  ) VALUES (
    v_record.id, v_record.source_key, v_record.receipt_number, v_record.member_name,
    v_record.staff_name, v_record.commission_amount, v_reason, auth.uid()
  );
  UPDATE public.membership_commissions
  SET cancelled_at = now(), cancelled_by = auth.uid(), cancellation_reason = v_reason,
      commission_before_cancellation = v_record.commission_amount,
      commission_amount = 0, updated_at = now()
  WHERE id = v_record.id;
  RETURN jsonb_build_object('ok', true, 'receipt_number', v_record.receipt_number,
    'removed_commission', v_record.commission_amount);
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_cancel_membership_commission(bigint,text,text,text,numeric,text) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.admin_cancel_membership_commission(bigint,text,text,text,numeric,text) TO authenticated;

COMMIT;

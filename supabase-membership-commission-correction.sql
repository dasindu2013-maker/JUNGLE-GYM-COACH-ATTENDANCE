-- Jungle Gym membership commission coach correction
-- Run this entire file once in Supabase Dashboard > SQL Editor.
-- Safe for existing records: it does not delete registrations, commissions,
-- attendance, payroll settings, or historical reports.

alter table public.membership_commissions
  add column if not exists original_staff_name text,
  add column if not exists manual_staff_override boolean not null default false,
  add column if not exists corrected_by uuid references public.profiles(id)
    on delete set null,
  add column if not exists corrected_at timestamptz,
  add column if not exists correction_reason text;

create table if not exists public.membership_commission_corrections (
  id bigint generated by default as identity primary key,
  commission_id bigint not null
    references public.membership_commissions(id) on delete cascade,
  previous_staff_name text not null,
  new_staff_name text not null,
  new_coach_id uuid not null
    references public.profiles(id) on delete restrict,
  reason text,
  corrected_by uuid not null
    references public.profiles(id) on delete restrict,
  corrected_at timestamptz not null default now()
);

create index if not exists membership_commission_corrections_commission_idx
  on public.membership_commission_corrections(commission_id, corrected_at desc);

alter table public.membership_commission_corrections
  enable row level security;

drop policy if exists "Admins view commission corrections"
  on public.membership_commission_corrections;

create policy "Admins view commission corrections"
on public.membership_commission_corrections
for select
to authenticated
using (public.is_admin());

create or replace function public.admin_reassign_membership_commission(
  p_commission_id bigint,
  p_new_coach_id uuid,
  p_reason text default null
)
returns public.membership_commissions
language plpgsql
security definer
set search_path = public
as $$
declare
  v_record public.membership_commissions%rowtype;
  v_new_staff_name text;
begin
  if not public.is_admin() then
    raise exception 'Only an admin can correct membership commissions';
  end if;

  select full_name
  into v_new_staff_name
  from public.profiles
  where id = p_new_coach_id
    and role = 'coach'
    and active is not false;

  if v_new_staff_name is null then
    raise exception 'Select an active coach';
  end if;

  select *
  into v_record
  from public.membership_commissions
  where id = p_commission_id
  for update;

  if not found then
    raise exception 'Membership commission record was not found';
  end if;

  if lower(trim(v_record.staff_name)) = lower(trim(v_new_staff_name)) then
    raise exception 'This registration is already assigned to that coach';
  end if;

  insert into public.membership_commission_corrections (
    commission_id,
    previous_staff_name,
    new_staff_name,
    new_coach_id,
    reason,
    corrected_by
  )
  values (
    v_record.id,
    v_record.staff_name,
    v_new_staff_name,
    p_new_coach_id,
    nullif(trim(coalesce(p_reason, '')), ''),
    auth.uid()
  );

  update public.membership_commissions
  set original_staff_name =
        coalesce(original_staff_name, v_record.staff_name),
      staff_name = v_new_staff_name,
      manual_staff_override = true,
      corrected_by = auth.uid(),
      corrected_at = now(),
      correction_reason = nullif(trim(coalesce(p_reason, '')), ''),
      updated_at = now()
  where id = v_record.id
  returning * into v_record;

  return v_record;
end;
$$;

revoke all on function public.admin_reassign_membership_commission(
  bigint, uuid, text
) from public;

grant execute on function public.admin_reassign_membership_commission(
  bigint, uuid, text
) to authenticated;

-- Preserve an admin correction when the Google Apps Script sync sends the
-- same registration again. Member, payment and receipt information can still
-- refresh, but a manually corrected staff assignment will not be overwritten.
create extension if not exists pgcrypto;

create or replace function public.sync_membership_commission(
  p_secret text,
  p_row jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_expected_hash text;
  v_source_key text;
  v_receipt text;
  v_staff text;
  v_member_name text;
  v_nic_number text;
  v_paid numeric(12,2);
  v_is_free boolean;
  v_commission numeric(12,2);
begin
  select secret_hash
    into v_expected_hash
  from public.integration_secrets
  where service_name = 'membership_commission';

  if v_expected_hash is null
     or encode(digest(coalesce(p_secret, ''), 'sha256'), 'hex')
        <> v_expected_hash then
    raise exception 'Invalid membership commission sync secret';
  end if;

  v_source_key := nullif(trim(p_row ->> 'source_key'), '');
  v_receipt := nullif(trim(p_row ->> 'receipt_number'), '');
  v_staff := nullif(trim(p_row ->> 'staff_name'), '');
  v_member_name := nullif(trim(p_row ->> 'member_name'), '');
  v_nic_number := nullif(trim(p_row ->> 'nic_number'), '');
  v_paid := greatest(
    coalesce((p_row ->> 'paid_amount')::numeric, 0),
    0
  );
  v_is_free := lower(coalesce(v_receipt, '')) like 'free%';
  v_commission := case
    when v_is_free then 0
    else round(v_paid * 0.10, 2)
  end;

  if v_source_key is null or v_receipt is null or v_staff is null then
    raise exception 'Missing required membership commission fields';
  end if;

  insert into public.membership_commissions as existing (
    source_key,
    receipt_number,
    member_name,
    nic_number,
    registration_type,
    payment_date,
    staff_name,
    paid_amount,
    commission_rate,
    commission_amount,
    is_free,
    updated_at
  )
  values (
    v_source_key,
    v_receipt,
    v_member_name,
    v_nic_number,
    coalesce(
      nullif(trim(p_row ->> 'registration_type'), ''),
      'Unknown'
    ),
    (p_row ->> 'payment_date')::date,
    v_staff,
    v_paid,
    0.10,
    v_commission,
    v_is_free,
    now()
  )
  on conflict (source_key) do update set
    receipt_number = excluded.receipt_number,
    member_name = excluded.member_name,
    nic_number = excluded.nic_number,
    registration_type = excluded.registration_type,
    payment_date = excluded.payment_date,
    staff_name = case
      when existing.manual_staff_override then existing.staff_name
      else excluded.staff_name
    end,
    paid_amount = excluded.paid_amount,
    commission_rate = excluded.commission_rate,
    commission_amount = excluded.commission_amount,
    is_free = excluded.is_free,
    updated_at = now();

  return jsonb_build_object(
    'ok', true,
    'commission_amount', v_commission,
    'is_free', v_is_free
  );
end;
$$;

revoke all on function public.sync_membership_commission(text, jsonb)
  from public;

grant execute on function public.sync_membership_commission(text, jsonb)
  to anon, authenticated;
